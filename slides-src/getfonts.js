/* One-time helper: download Public Sans and Special Elite (SIL Open Font License) from Google Fonts,
   latin and latin-ext only, and write them as embedded @font-face rules to slides-src/fonts-lesson.css.
   The slide pages then load no fonts from any other server. Run: node slides-src/getfonts.js */
const fs = require("fs"), https = require("https");
const URL = "https://fonts.googleapis.com/css2?family=Public+Sans:ital,wght@0,400;0,700;1,400&family=Special+Elite&display=swap";
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";
const get = (u) => new Promise((ok, no) => https.get(u, { headers: { "User-Agent": UA } }, (r) => { const b = []; r.on("data", (c) => b.push(c)); r.on("end", () => r.statusCode === 200 ? ok(Buffer.concat(b)) : no(new Error(u + " " + r.statusCode))); }).on("error", no));
(async () => {
  const css = (await get(URL)).toString();
  const blocks = css.split(/(?=\/\* [a-z-]+ \*\/)/).filter((b) => /^\/\* (latin|latin-ext) \*\//.test(b));
  let out = "/* Public Sans and Special Elite, SIL Open Font License 1.1, from Google Fonts (latin, latin-ext). Generated by slides-src/getfonts.js. */\n";
  for (const b of blocks) {
    const u = /url\((https:[^)]+\.woff2)\)/.exec(b)[1]; const data = (await get(u)).toString("base64");
    out += b.replace(/url\([^)]+\)\s*format\('woff2'\)/, `url(data:font/woff2;base64,${data}) format('woff2')`).trim() + "\n";
  }
  fs.writeFileSync(__dirname + "/fonts-lesson.css", out);
  console.log("faces:", blocks.length, "bytes:", out.length);
})();
